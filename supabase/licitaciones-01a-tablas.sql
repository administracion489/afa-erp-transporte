-- UN DOCUMENTO POR LICITACIÓN (doc jsonb) con bloqueo optimista: se guarda con UPDATE … where version = v y el
-- trigger sube version, sella quién/cuándo y no deja cambiar quién la creó. Los datos del concurso van SOLO en
-- columnas. LA EMISIÓN ES LA CONSTANCIA: se inserta una vez, no se edita ni se borra (01b no da UPDATE ni DELETE)
-- y frena el borrado de su licitación. licitacion_analisis la escribe SOLO el servidor (service-role).
create table if not exists public.licitaciones (
  id             bigint generated by default as identity primary key,
  nombre         text not null constraint licitaciones_nombre_ck check (char_length(btrim(nombre)) between 1 and 200),
  cliente_id     bigint references public.clientes(id) on delete set null,
  cliente_nombre text not null constraint licitaciones_cliente_ck check (char_length(cliente_nombre) <= 200),
  codigo         text constraint licitaciones_codigo_ck check (char_length(codigo) <= 80),
  objeto         text constraint licitaciones_objeto_ck check (char_length(objeto) <= 2000),
  atencion       text constraint licitaciones_atencion_ck check (char_length(atencion) <= 200),
  fecha_consultas date, fecha_presentacion date, hora_presentacion time, fecha_inicio_servicio date,
  plazo_meses    smallint constraint licitaciones_plazo_ck check (plazo_meses between 1 and 240),
  estado         text not null default 'preparacion' constraint licitaciones_estado_ck check (estado in
                   ('preparacion', 'presentada', 'adjudicada', 'no_adjudicada', 'desierta', 'descartada')),
  archivada      boolean not null default false,
  doc            jsonb not null default '{}'::jsonb constraint licitaciones_doc_ck
                   check (jsonb_typeof(doc) = 'object' and pg_column_size(doc) <= 3000000),
  version        integer not null default 1 constraint licitaciones_version_ck check (version >= 1),
  creado_por     uuid default auth.uid() references public.usuarios(id) on delete set null,
  creado_en      timestamptz not null default now(), actualizado_por uuid references public.usuarios(id) on delete set null,
  actualizado_en timestamptz not null default now()
);
-- La lista (no archivadas, por presentación, id de desempate = orden total para paginar) y por cliente.
create index if not exists idx_licitaciones_lista on public.licitaciones (archivada, fecha_presentacion desc nulls last, id desc);
create index if not exists idx_licitaciones_cliente on public.licitaciones (cliente_id) where cliente_id is not null;
-- Al crear: version 1 y quien crea es la sesión. Al guardar: version + 1, quién y cuándo. Quién la creó no
-- cambia; solo puede quedar en null (el on delete set null de usuarios también pasa por este trigger).
create or replace function public.fn_licitaciones_sellar() returns trigger
language plpgsql security invoker set search_path = public, pg_temp as $$ begin
  if tg_op = 'INSERT' then
    new.version := 1; new.creado_en := now(); new.creado_por := coalesce(auth.uid(), new.creado_por);
    new.actualizado_en := new.creado_en; new.actualizado_por := new.creado_por;
  else
    new.version := old.version + 1; new.actualizado_en := now(); new.actualizado_por := auth.uid();
    new.creado_en := old.creado_en; if new.creado_por is not null then new.creado_por := old.creado_por; end if;
  end if; return new; end $$;
drop trigger if exists trg_licitaciones_sellar on public.licitaciones;
create trigger trg_licitaciones_sellar before insert or update on public.licitaciones
  for each row execute function public.fn_licitaciones_sellar();

create table if not exists public.licitacion_analisis (
  id            bigint generated by default as identity primary key,
  licitacion_id bigint not null references public.licitaciones(id) on delete cascade,
  estado        text not null default 'en_curso' constraint licitacion_analisis_estado_ck check (estado in ('en_curso', 'listo', 'error')),
  usuario_id    uuid references public.usuarios(id) on delete set null,
  modelo        text not null constraint licitacion_analisis_modelo_ck check (char_length(modelo) between 1 and 100),
  archivos jsonb not null default '[]'::jsonb, texto_sha256 text, resultado jsonb, avisos jsonb not null default '[]'::jsonb,
  error         text constraint licitacion_analisis_error_ck check (char_length(error) <= 1000),
  tokens_entrada integer, tokens_salida integer, costo_usd numeric(10,4),
  creado_en timestamptz not null default now(), terminado_en timestamptz,
  constraint licitacion_analisis_listas_ck check (jsonb_typeof(archivos) = 'array' and jsonb_typeof(avisos) = 'array'),
  constraint licitacion_analisis_uso_ck check (coalesce(tokens_entrada, 0) >= 0 and coalesce(tokens_salida, 0) >= 0 and coalesce(costo_usd, 0) >= 0)
);
-- UN análisis en curso por licitación (el doble clic choca aquí; uno colgado lo cierra el servidor); el tope diario.
create unique index if not exists uq_licitacion_analisis_en_curso on public.licitacion_analisis (licitacion_id) where estado = 'en_curso';
create index if not exists idx_licitacion_analisis_creado on public.licitacion_analisis (creado_en desc);
create index if not exists idx_licitacion_analisis_lic on public.licitacion_analisis (licitacion_id, creado_en desc);

create table if not exists public.licitacion_emisiones (
  id            bigint generated by default as identity primary key,
  licitacion_id bigint not null references public.licitaciones(id) on delete restrict,
  version       integer not null constraint licitacion_emisiones_version_ck check (version >= 1),
  carpeta       uuid not null constraint uq_licitacion_emisiones_carpeta unique,
  emitido_por   uuid not null default auth.uid() references public.usuarios(id),          -- constancia: sin set null
  emitido_en    timestamptz not null default now(),
  doc_version   integer not null constraint licitacion_emisiones_doc_version_ck check (doc_version >= 1),
  firma         text not null constraint licitacion_emisiones_firma_ck check (firma ~ '^[0-9a-f]{64}$'),
  foto          jsonb not null constraint licitacion_emisiones_foto_ck check (jsonb_typeof(foto) = 'object' and pg_column_size(foto) <= 6000000),
  archivos jsonb not null default '[]'::jsonb, hallazgos jsonb not null default '[]'::jsonb, omitidos jsonb not null default '[]'::jsonb,
  nota          text constraint licitacion_emisiones_nota_ck check (char_length(nota) <= 2000),
  constraint uq_licitacion_emisiones_version unique (licitacion_id, version),
  constraint licitacion_emisiones_listas_ck check (jsonb_typeof(archivos) = 'array' and jsonb_typeof(hallazgos) = 'array'
    and jsonb_typeof(omitidos) = 'array')
);
-- Quién y cuándo los pone la base, no el navegador (con service-role auth.uid() es null y vale lo que se mande).
create or replace function public.fn_licitacion_emisiones_sellar() returns trigger
language plpgsql security invoker set search_path = public, pg_temp as $$
begin new.emitido_en := now(); new.emitido_por := coalesce(auth.uid(), new.emitido_por); return new; end $$;
drop trigger if exists trg_licitacion_emisiones_sellar on public.licitacion_emisiones;
create trigger trg_licitacion_emisiones_sellar before insert on public.licitacion_emisiones
  for each row execute function public.fn_licitacion_emisiones_sellar();
do $$ declare t text; begin foreach t in array array['licitaciones', 'licitacion_analisis', 'licitacion_emisiones'] loop
  execute format('alter table public.%I enable row level security', t); execute format('revoke all on public.%I from anon', t);
end loop; end $$;
-- Verificación (solo lee). Debe salir: 3 tablas · RLS true · políticas 0 (con 01b ya corrida: 1, 2 y 1) · restricciones (CHECK, FK y
-- únicas) 7 en licitacion_analisis, 10 en licitacion_emisiones y 12 en licitaciones · el trigger de sellado en las dos.
select c.relname::text as tabla, 'RLS ' || c.relrowsecurity || ' · políticas ' || (select count(*) from pg_policies p where p.schemaname = 'public' and p.tablename = c.relname)
       || ' · restricciones ' || (select count(*) from pg_constraint k where k.conrelid = c.oid and k.contype in ('c', 'f', 'u'))
       || ' · triggers ' || coalesce((select string_agg(tgname, ', ') from pg_trigger t where t.tgrelid = c.oid and not t.tgisinternal), '—') as detalle
  from pg_class c where c.relnamespace = 'public'::regnamespace and c.relname in ('licitaciones', 'licitacion_analisis', 'licitacion_emisiones') order by 1;
