-- ── 3) Dedupe de alertas de ciclo de vida (una fila por reserva) ──────────────
create table if not exists public.avisos_conductor_estado (
  reserva_id          bigint primary key,
  conductor_avisado   bigint,
  vehiculo_avisado    bigint,
  hora_avisada        text,
  cancelacion_avisada boolean not null default false,
  aviso_90_at         timestamptz,      -- recordatorio por anticipación ya enviado
  no_inicio_at        timestamptz,
  gps_silencio_at     timestamptz,      -- null = GPS ok / re-armado
  updated_at          timestamptz default now()
);

-- BACKFILL de baseline: siembra el estado de las reservas YA asignadas al correr la
-- migración por PRIMERA vez, para que el PRIMER tick NO las trate como "asignación nueva"
-- y dispare un blast masivo de WhatsApp. Solo corre si la tabla está VACÍA: así re-ejecutar
-- la migración (con el sistema ya en producción) NO siembra baseline de reservas nuevas
-- —que aún no fueron notificadas— y por tanto no les suprime su aviso de asignación real.
do $$
begin
  if not exists (select 1 from public.avisos_conductor_estado) then
    insert into public.avisos_conductor_estado (reserva_id, conductor_avisado, vehiculo_avisado, hora_avisada)
    select id, conductor_id, vehiculo_id, coalesce(substr(hora_servicio::text, 1, 5), '-')
    from public.reservas
    where tipo_asignacion = 'propio' and conductor_id is not null and estado <> 'cancelada';
  end if;
end$$;

-- ── 3b) Dedupe universal insert-once (avisos por día: recordatorios, docs, solape,
--       jornada). ref = reserva_id / conductor_id / "conductor_id:doc" según el tipo.
--       El motor inserta y un 23505 significa "ya se envió hoy" → no reenvía.
create table if not exists public.alerta_enviada (
  id         bigint generated by default as identity primary key,
  clave      text not null,
  ref        text not null,
  fecha      date not null,
  created_at timestamptz default now()
);
create unique index if not exists uq_alerta_enviada on public.alerta_enviada(clave, ref, fecha);

-- ── 3c) Canales de notificación al PASAJERO (anti-spam) ───────────────────────
--   Los avisos al pasajero (confirmación, recordatorio, "bus llegó") salían SIEMPRE
--   por los 3 canales (push app + email + WhatsApp) = spam. Aquí se controla cada
--   canal y, con "solo_sin_app", se manda ese canal ÚNICAMENTE a quien NO tiene la
--   app (sin suscripción push activa). Default: con app → solo push; sin app → email+WhatsApp.
create table if not exists public.config_canales (
  id                    int primary key default 1,
  push_activo           boolean not null default true,
  email_activo          boolean not null default true,
  email_solo_sin_app    boolean not null default true,
  whatsapp_activo       boolean not null default true,
  whatsapp_solo_sin_app boolean not null default true,
  updated_at            timestamptz default now(),
  constraint config_canales_unica check (id = 1)
);
insert into public.config_canales (id) values (1) on conflict (id) do nothing;

-- ── 4) RLS (patrón authenticated, como config_mantenimiento) ──────────────────
alter table public.alerta_destinatarios    enable row level security;
alter table public.alerta_config           enable row level security;
alter table public.avisos_conductor_estado enable row level security;
alter table public.alerta_enviada          enable row level security;
alter table public.config_canales          enable row level security;

-- Helper: ¿el usuario de la sesión puede administrar la config? (admin o módulo
-- configuracion). SECURITY DEFINER para leer usuarios/permisos_usuario sin depender de
-- su RLS. El motor usa service-role (ignora RLS), así que esto solo afecta a la UI.
create or replace function public.puede_config_alertas() returns boolean
  language sql stable security definer set search_path = public as $fn$
  select exists (
    select 1 from public.usuarios u
    where u.id = auth.uid() and coalesce(u.activo, true)
      and (u.rol = 'admin' or exists (
        select 1 from public.permisos_usuario p
        where p.usuario_id = u.id and p.modulo = 'configuracion' and coalesce(p.permitido, false)))
  );
$fn$;

do $$
begin
  -- Directorio + config + canales: SOLO admin/módulo configuración (controlan mensajería
  -- saliente y el on/off de alertas de seguridad; no dejar a cualquier autenticado).
  drop policy if exists "alerta_dest_auth"     on public.alerta_destinatarios;
  drop policy if exists "alerta_config_auth"   on public.alerta_config;
  if not exists (select 1 from pg_policies where tablename='alerta_destinatarios' and policyname='alerta_dest_config') then
    create policy "alerta_dest_config" on public.alerta_destinatarios
      for all using (public.puede_config_alertas()) with check (public.puede_config_alertas());
  end if;
  if not exists (select 1 from pg_policies where tablename='alerta_config' and policyname='alerta_config_config') then
    create policy "alerta_config_config" on public.alerta_config
      for all using (public.puede_config_alertas()) with check (public.puede_config_alertas());
  end if;
  if not exists (select 1 from pg_policies where tablename='avisos_conductor_estado' and policyname='avisos_estado_auth') then
    create policy "avisos_estado_auth" on public.avisos_conductor_estado
      for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
  end if;
  if not exists (select 1 from pg_policies where tablename='alerta_enviada' and policyname='alerta_enviada_auth') then
    create policy "alerta_enviada_auth" on public.alerta_enviada
      for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
  end if;
  if not exists (select 1 from pg_policies where tablename='config_canales' and policyname='config_canales_config') then
    create policy "config_canales_config" on public.config_canales
      for all using (public.puede_config_alertas()) with check (public.puede_config_alertas());
  end if;
end$$;

