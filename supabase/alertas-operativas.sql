-- ============================================================
-- Centro de control de mensajes / alertas operativas (WhatsApp)
-- Ejecutar en Supabase SQL Editor. Idempotente.
-- ============================================================
-- Modelo:
--   • alerta_destinatarios : directorio editable de personas que reciben alertas
--     (nombre + función + WhatsApp). El usuario los administra desde la UI.
--   • alerta_config        : una fila por TIPO de mensaje, con su activación, cuándo
--     se envía (evento / anticipación en min / hora fija) y a quién (conductor,
--     pasajero, y qué contactos del directorio via `destinatarios` jsonb de ids).
--   • avisos_conductor_estado : dedupe de las alertas de ciclo de vida por reserva.
-- El motor (/api/alertas-flota/tick) lee esta config; nada está hardcodeado.
-- ============================================================

-- ── 1) Directorio de destinatarios ────────────────────────────────────────────
create table if not exists public.alerta_destinatarios (
  id              bigint generated by default as identity primary key,
  nombre          text not null,
  funcion         text,                  -- p.ej. "Coordinador de Operaciones", "Administración"
  telefono        text not null,         -- WhatsApp E.164 o 9 dígitos (se normaliza al enviar)
  activo          boolean not null default true,
  es_contingencia boolean not null default false, -- su número aparece en los mensajes al conductor
  created_at      timestamptz default now()
);
alter table public.alerta_destinatarios add column if not exists es_contingencia boolean not null default false;

-- ── 2) Configuración por tipo de mensaje ──────────────────────────────────────
create table if not exists public.alerta_config (
  clave               text primary key,          -- id estable del tipo de alerta
  nombre              text not null,              -- etiqueta visible
  descripcion         text,
  activo              boolean not null default true,
  -- Cuándo se envía:
  modo_tiempo         text not null default 'evento'
                      check (modo_tiempo in ('evento','anticipacion','hora_fija')),
  min_anticipacion    int,                        -- modo 'anticipacion': X min antes del servicio
  hora_fija           text,                       -- modo 'hora_fija': "HH:MM" (Lima)
  umbral              int,                         -- genérico: gracia(min) / silencio(min) / días
  -- A quién:
  notifica_conductor  boolean not null default false,
  notifica_pasajero   boolean not null default false,
  destinatarios       jsonb not null default '[]'::jsonb,  -- ids de alerta_destinatarios
  -- Plantillas Meta (por nombre; deben existir/estar aprobadas):
  plantilla           text,                        -- para conductor/pasajero
  plantilla_directorio text default 'coordinador_alerta', -- para el personal del directorio
  updated_at          timestamptz default now()
);

