-- traslados-01-tablas.sql — Zonas, categorías y tarifas de TRASLADO (cotización automática).
-- NO la corre el deploy. Sin ella, /tarifario → «Zonas y traslados» lo dice en ámbar.
--
-- Una tarifa de traslado es por PAR DE ZONAS sin sentido (A↔B = B↔A): se guarda siempre con
-- zona_a_id <= zona_b_id, y así un upsert simple por (a, b, categoría, moneda) basta.
-- La zona de una dirección la decide lib/traslados/motor.ts: punto (geocerca) > subzona > distrito.
-- Correr entero con Run. Es idempotente.

create table if not exists public.zonas_traslado (
  id         bigint generated by default as identity primary key,
  nombre     text not null,
  tipo       text not null check (tipo in ('distrito','subzona','punto')),
  padre_id   bigint references public.zonas_traslado(id) on delete cascade,
  sector     text,
  alias      text[] not null default '{}',
  lat        double precision,
  lng        double precision,
  radio_m    integer,
  orden      integer not null default 0,
  activo     boolean not null default true,
  notas      text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint zonas_traslado_forma check (
    (tipo = 'distrito' and padre_id is null)
    or (tipo = 'subzona' and padre_id is not null and lat is not null and lng is not null)
    or (tipo = 'punto' and padre_id is null and lat is not null and lng is not null and coalesce(radio_m, 0) > 0)
  )
);
create unique index if not exists uq_zonas_traslado_nombre on public.zonas_traslado (lower(nombre));

create table if not exists public.traslado_categorias (
  clave          text primary key,
  nombre         text not null,
  capacidad      integer not null check (capacidad > 0),
  maletas_bodega integer not null default 0 check (maletas_bodega >= 0),
  tipo_vehiculo  text,
  orden          integer not null default 0,
  activo         boolean not null default true,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create table if not exists public.tarifas_traslado (
  id           bigint generated by default as identity primary key,
  zona_a_id    bigint not null references public.zonas_traslado(id) on delete cascade,
  zona_b_id    bigint not null references public.zonas_traslado(id) on delete cascade,
  categoria    text not null references public.traslado_categorias(clave) on update cascade on delete restrict,
  moneda       text not null check (moneda in ('PEN','USD')),
  precio_tramo numeric(12,2) not null check (precio_tramo > 0),
  activo       boolean not null default true,
  notas        text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint tarifas_traslado_orden check (zona_a_id <= zona_b_id),
  constraint uq_tarifas_traslado unique (zona_a_id, zona_b_id, categoria, moneda)
);

create table if not exists public.traslados_config (
  id                  integer primary key default 1 check (id = 1),
  validez_dias        integer not null default 30 check (validez_dias > 0),
  espera_gratis_min   integer not null default 30 check (espera_gratis_min >= 0),
  consideraciones     text[] not null default '{}',
  consideraciones_usd text[] not null default '{}',
  updated_at          timestamptz not null default now()
);
insert into public.traslados_config (id) values (1) on conflict (id) do nothing;

create or replace function public.fn_traslados_updated_at() returns trigger
language plpgsql set search_path = public as $$
begin
  new.updated_at := now();
  return new;
end $$;

-- updated_at y RLS de las cuatro tablas: solo usuarios del ERP (la anon key va en el JavaScript
-- público, así que anon = cualquiera en internet).
do $$ declare t text; begin
  foreach t in array array['zonas_traslado','traslado_categorias','tarifas_traslado','traslados_config'] loop
    execute format('drop trigger if exists trg_%s_upd on public.%I', t, t);
    execute format('create trigger trg_%s_upd before update on public.%I for each row execute function public.fn_traslados_updated_at()', t, t);
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists p_%s_auth on public.%I', t, t);
    execute format('create policy p_%s_auth on public.%I for all to authenticated using (true) with check (true)', t, t);
    execute format('revoke all on public.%I from anon', t);
  end loop;
end $$;
