-- traslados-01-tablas.sql — Zonas, categorías y tarifas de TRASLADO (cotización automática).
-- NO la corre el deploy. Sin ella, /tarifario → «Zonas y traslados» lo dice en ámbar.
-- El par de zonas no tiene sentido (A↔B = B↔A): se guarda con zona_a_id <= zona_b_id.
-- LEER: cualquier usuario del ERP. ESCRIBIR: solo con el módulo «tarifas» (o admin): estos
-- precios los envía la IA a clientes sin que una persona los revise. Correr entero con Run.

create or replace function public.fn_puede_modulo(p_uid uuid, p_modulo text)
returns boolean language sql stable security definer set search_path = public, pg_temp as $$
  select exists (
    select 1 from public.usuarios u
     where u.id = p_uid and coalesce(u.activo, true) = true
       and (u.rol = 'admin'
            or exists (select 1 from public.permisos_usuario pu
                        where pu.usuario_id = p_uid and pu.modulo = p_modulo and pu.permitido = true))
  );
$$;
revoke all on function public.fn_puede_modulo(uuid, text) from public, anon;
grant execute on function public.fn_puede_modulo(uuid, text) to authenticated;

create table if not exists public.zonas_traslado (
  id         bigint generated by default as identity primary key,
  nombre     text not null,
  tipo       text not null check (tipo in ('distrito','subzona','punto')),
  padre_id   bigint references public.zonas_traslado(id) on delete cascade,
  sector     text,
  alias      text[] not null default '{}',
  lat        double precision check (lat between -90 and 90),
  lng        double precision check (lng between -180 and 180),
  radio_m    integer check (radio_m between 1 and 10000),
  orden      integer not null default 0,
  activo     boolean not null default true,
  notas      text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint zonas_traslado_forma check (
    (tipo = 'distrito' and padre_id is null)
    or (tipo = 'subzona' and padre_id is not null and lat is not null and lng is not null)
    or (tipo = 'punto' and padre_id is null and lat is not null and lng is not null and radio_m is not null))
);
create unique index if not exists uq_zonas_traslado_nombre on public.zonas_traslado (lower(nombre));

create table if not exists public.traslado_categorias (
  clave          text primary key,
  nombre         text not null,
  capacidad      integer not null check (capacidad between 1 and 100),
  maletas_bodega integer not null default 0 check (maletas_bodega between 0 and 200),
  tipo_vehiculo  text,
  orden          integer not null default 0,
  activo         boolean not null default true,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create table if not exists public.tarifas_traslado (
  id           bigint generated by default as identity primary key,
  zona_a_id    bigint not null references public.zonas_traslado(id) on delete cascade,
  zona_b_id    bigint not null references public.zonas_traslado(id) on delete cascade,
  categoria    text not null references public.traslado_categorias(clave) on update cascade on delete restrict,
  moneda       text not null check (moneda in ('PEN','USD')),
  precio_tramo numeric(12,2) not null check (precio_tramo > 0),
  activo       boolean not null default true,
  notas        text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint tarifas_traslado_orden check (zona_a_id <= zona_b_id),
  constraint uq_tarifas_traslado unique (zona_a_id, zona_b_id, categoria, moneda)
);

create table if not exists public.traslados_config (
  id                  integer primary key default 1 check (id = 1),
  validez_dias        integer not null default 30 check (validez_dias between 1 and 365),
  espera_gratis_min   integer not null default 30 check (espera_gratis_min between 0 and 600),
  consideraciones     text[] not null default '{}',
  consideraciones_usd text[] not null default '{}',
  updated_at          timestamptz not null default now()
);
insert into public.traslados_config (id) values (1) on conflict (id) do nothing;

create or replace function public.fn_traslados_updated_at() returns trigger
language plpgsql set search_path = public as $$
begin
  new.updated_at := now();
  return new;
end $$;

do $$ declare t text; begin
  foreach t in array array['zonas_traslado','traslado_categorias','tarifas_traslado','traslados_config'] loop
    execute format('drop trigger if exists trg_%s_upd on public.%I', t, t);
    execute format('create trigger trg_%s_upd before update on public.%I for each row execute function public.fn_traslados_updated_at()', t, t);
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists p_%s_auth on public.%I', t, t);
    execute format('drop policy if exists p_%s_leer on public.%I', t, t);
    execute format('drop policy if exists p_%s_escribir on public.%I', t, t);
    execute format('create policy p_%s_leer on public.%I for select to authenticated using (true)', t, t);
    execute format('create policy p_%s_escribir on public.%I for all to authenticated using (public.fn_puede_modulo(auth.uid(), ''tarifas'')) with check (public.fn_puede_modulo(auth.uid(), ''tarifas''))', t, t);
    execute format('revoke all on public.%I from anon', t);
  end loop;
end $$;
