create table if not exists public.experiencia_empresa (
  id                  bigint generated by default as identity primary key,
  cliente_id          bigint references public.clientes(id) on delete set null,
  cliente_nombre      text not null constraint experiencia_cliente_ck check (char_length(btrim(cliente_nombre)) between 1 and 200),
  cliente_ruc         text constraint experiencia_ruc_ck check (cliente_ruc ~ '^[0-9]{11}$'),
  contacto_nombre     text, contacto_cargo text, contacto_telefono text, contacto_email text,
  objeto              text not null default 'Transporte de personal'
                        constraint experiencia_objeto_ck check (char_length(btrim(objeto)) between 1 and 500),
  sector              text constraint experiencia_sector_ck check (char_length(sector) <= 80),
  zona                text constraint experiencia_zona_ck check (char_length(zona) <= 200),
  inicio              date not null,
  fin                 date,
  vigente             boolean not null default false,
  sustento_tipo       text constraint experiencia_sustento_tipo_ck
                        check (sustento_tipo in ('oc', 'factura', 'carta', 'contrato', 'conformidad', 'otro')),
  sustento_ref        text constraint experiencia_sustento_ref_ck check (char_length(sustento_ref) <= 120),
  sustento_fecha      date,
  importe             numeric(14,2) constraint experiencia_importe_ck check (importe >= 0),
  moneda              text not null default 'PEN' constraint experiencia_moneda_ck check (moneda in ('PEN', 'USD')),
  importe_incluye_igv boolean,
  sustentos           jsonb not null default '[]'::jsonb constraint experiencia_sustentos_ck check (jsonb_typeof(sustentos) = 'array'),
  notas               text constraint experiencia_notas_ck check (char_length(notas) <= 2000),
  activo              boolean not null default true,
  creado_por          uuid default auth.uid() references public.usuarios(id) on delete set null,
  creado_en           timestamptz not null default now(),
  actualizado_en      timestamptz not null default now(),
  constraint experiencia_fin_ck check (fin is null or fin >= inicio),
  constraint experiencia_contacto_ck check (char_length(coalesce(contacto_nombre, '')) <= 120
    and char_length(coalesce(contacto_cargo, '')) <= 120 and char_length(coalesce(contacto_telefono, '')) <= 120
    and char_length(coalesce(contacto_email, '')) <= 120)
);
-- El catálogo: activos primero, del contrato más reciente al más antiguo (id de desempate).
create index if not exists idx_experiencia_empresa_lista on public.experiencia_empresa (activo, inicio desc, id desc);

-- Al crear, quien crea es la sesión; al guardar, actualizado_en. Quién y cuándo se creó no cambian (creado_por solo
-- puede quedar en null: el on delete set null de usuarios también pasa por aquí).
create or replace function public.fn_experiencia_empresa_sellar() returns trigger
language plpgsql security invoker set search_path = public, pg_temp as $$ begin
  if tg_op = 'INSERT' then
    new.creado_por := coalesce(auth.uid(), new.creado_por); new.creado_en := now(); new.actualizado_en := new.creado_en;
  else
    new.actualizado_en := now(); new.creado_en := old.creado_en;
    if new.creado_por is not null then new.creado_por := old.creado_por; end if;
  end if; return new; end $$;
drop trigger if exists trg_experiencia_empresa_sellar on public.experiencia_empresa;
create trigger trg_experiencia_empresa_sellar before insert or update on public.experiencia_empresa
  for each row execute function public.fn_experiencia_empresa_sellar();

alter table public.experiencia_empresa enable row level security;
do $$ declare p record; begin
  for p in select policyname from pg_policies where schemaname = 'public' and tablename = 'experiencia_empresa' loop
    execute format('drop policy %I on public.experiencia_empresa', p.policyname);
  end loop;
end $$;
create policy experiencia_empresa_modulo on public.experiencia_empresa for all to authenticated
  using ((select public.fn_puede_modulo((select auth.uid()), 'licitaciones')))
  with check ((select public.fn_puede_modulo((select auth.uid()), 'licitaciones')));
revoke all on public.experiencia_empresa from anon;
revoke truncate on public.experiencia_empresa from authenticated;

-- Verificación (solo lee): RLS true · 1 política ALL · anon «ninguno» · 15 restricciones (13 CHECK, 2 FK) · el trigger.
select 'tabla' as que, 'experiencia_empresa' as nombre, 'RLS ' || relrowsecurity || ' · políticas ' || (select string_agg(policyname
       || ' ' || cmd, ', ') from pg_policies where schemaname = 'public' and tablename = 'experiencia_empresa') as detalle
  from pg_class where oid = 'public.experiencia_empresa'::regclass
union all select 'permiso ' || r, 'experiencia_empresa', coalesce(string_agg(p, ', ' order by p)
       filter (where has_table_privilege(r, 'public.experiencia_empresa', p)), 'ninguno')
  from unnest(array['anon', 'authenticated']) r, unnest(array['SELECT', 'INSERT', 'UPDATE', 'DELETE']) p group by r
union all select 'restricciones', 'experiencia_empresa', count(*)::text from pg_constraint
 where conrelid = 'public.experiencia_empresa'::regclass and contype in ('c', 'f')
union all select 'trigger', tgname::text, pg_get_triggerdef(oid) from pg_trigger
 where tgrelid = 'public.experiencia_empresa'::regclass and not tgisinternal
order by 1, 2;
